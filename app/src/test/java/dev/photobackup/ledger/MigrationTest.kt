package dev.photobackup.ledger

import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class MigrationTest {
    @Test fun v1RowsSurviveAndNewTableWorks() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val file = ctx.getDatabasePath("migration-test.db")
        file.parentFile?.mkdirs()
        file.delete()

        // Exact v1 schema, as generated by Room for AppDatabase version 1.
        val v1 = SQLiteDatabase.openOrCreateDatabase(file, null)
        v1.execSQL(
            "CREATE TABLE IF NOT EXISTS `LedgerEntry` (`mediaId` INTEGER NOT NULL, `localUri` TEXT NOT NULL, " +
                "`displayName` TEXT NOT NULL, `relativePath` TEXT NOT NULL, `sizeBytes` INTEGER NOT NULL, " +
                "`dateTakenMs` INTEGER NOT NULL, `dateModifiedSec` INTEGER NOT NULL, `isVideo` INTEGER NOT NULL, " +
                "`localSha256` TEXT, `remotePath` TEXT, `partPath` TEXT, `status` TEXT NOT NULL, " +
                "`lastError` TEXT, `updatedAtMs` INTEGER NOT NULL, PRIMARY KEY(`mediaId`))"
        )
        v1.execSQL(
            "INSERT INTO LedgerEntry VALUES (7, 'content://media/7', 'a.jpg', 'DCIM/Camera/', 100, 1000, 10, 0, " +
                "'abc', 'Backup/Pixel/Camera/2024/a.jpg', NULL, 'VERIFIED', NULL, 5)"
        )
        v1.version = 1
        v1.close()

        val db = Room.databaseBuilder(ctx, AppDatabase::class.java, "migration-test.db")
            .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5).allowMainThreadQueries().build()
        try {
            val e = db.ledgerDao().get(7)!!
            assertEquals("Backup/Pixel/Camera/2024/a.jpg", e.remotePath)
            assertEquals(BackupStatus.VERIFIED, e.status)
            assertNull(e.movingTo)
            assertEquals(emptyList<LedgerEntry>(), db.ledgerDao().withMovingTo())

            val dao = db.folderAssignmentDao()
            assertNull(dao.get(7))
            dao.set(FolderAssignment(7, "Dog"))
            assertEquals(FolderAssignment(7, "Dog"), dao.get(7))
            dao.set(FolderAssignment(7, "Cat"))
            assertEquals(listOf(FolderAssignment(7, "Cat")), dao.all())
            dao.clear(7)
            assertNull(dao.get(7))

            db.ledgerDao().upsert(e.copy(movingTo = "Backup/Pixel/Dog/2024/a.jpg"))
            assertEquals(listOf(7L), db.ledgerDao().withMovingTo().map { it.mediaId })
        } finally {
            db.close()
        }
    }

    private val v2LedgerSql =
        "CREATE TABLE IF NOT EXISTS `LedgerEntry` (`mediaId` INTEGER NOT NULL, `localUri` TEXT NOT NULL, " +
            "`displayName` TEXT NOT NULL, `relativePath` TEXT NOT NULL, `sizeBytes` INTEGER NOT NULL, " +
            "`dateTakenMs` INTEGER NOT NULL, `dateModifiedSec` INTEGER NOT NULL, `isVideo` INTEGER NOT NULL, " +
            "`localSha256` TEXT, `remotePath` TEXT, `partPath` TEXT, `status` TEXT NOT NULL, `lastError` TEXT, " +
            "`updatedAtMs` INTEGER NOT NULL, `movingTo` TEXT, PRIMARY KEY(`mediaId`))"
    private val v2AssignmentSql =
        "CREATE TABLE IF NOT EXISTS `FolderAssignment` (`mediaId` INTEGER NOT NULL, `folder` TEXT NOT NULL, " +
            "PRIMARY KEY(`mediaId`))"

    @Test fun v2RowsSurviveAndNewColumnsAndTablesWork() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val file = ctx.getDatabasePath("migration-test-v2.db")
        file.parentFile?.mkdirs()
        file.delete()

        // Exact v2 schema, as generated by Room for AppDatabase version 2.
        val v2 = SQLiteDatabase.openOrCreateDatabase(file, null)
        v2.execSQL(v2LedgerSql)
        v2.execSQL(v2AssignmentSql)
        v2.execSQL(
            "INSERT INTO LedgerEntry VALUES (7, 'content://media/7', 'a.jpg', 'DCIM/Camera/', 100, 1000, 10, 0, " +
                "'abc', 'Backup/Pixel/Camera/2024/a.jpg', NULL, 'VERIFIED', NULL, 5, 'Backup/Pixel/Dog/2024/a.jpg')"
        )
        v2.execSQL(
            "INSERT INTO LedgerEntry VALUES (8, 'content://media/8', 'b.mp4', 'DCIM/Camera/', 200, 2000, 20, 1, " +
                "NULL, NULL, 'x.part', 'UPLOADING', 'boom', 6, NULL)"
        )
        v2.execSQL("INSERT INTO FolderAssignment VALUES (7, 'Dog')")
        v2.version = 2
        v2.close()

        val db = Room.databaseBuilder(ctx, AppDatabase::class.java, "migration-test-v2.db")
            .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5).allowMainThreadQueries().build()
        try {
            val a = db.ledgerDao().get(7)!!
            assertEquals("Backup/Pixel/Camera/2024/a.jpg", a.remotePath)
            assertEquals(BackupStatus.VERIFIED, a.status)
            assertEquals("Backup/Pixel/Dog/2024/a.jpg", a.movingTo)
            assertNull(a.binRequestedAt)
            assertNull(a.binPath)
            assertNull(a.binnedAt)
            val b = db.ledgerDao().get(8)!!
            assertEquals(BackupStatus.UPLOADING, b.status)
            assertEquals("x.part", b.partPath)
            assertEquals("boom", b.lastError)
            assertEquals(FolderAssignment(7, "Dog"), db.folderAssignmentDao().get(7))

            db.ledgerDao().upsert(a.copy(status = BackupStatus.BINNED, binRequestedAt = 1, binPath = "p", binnedAt = 2))
            assertEquals(2L, db.ledgerDao().get(7)!!.binnedAt)

            val d = db.reviewDecisionDao()
            d.upsert(ReviewDecision(7, dev.photobackup.review.ReviewAction.JUNK, 10))
            assertEquals(7L, d.lastDecided()!!.mediaId)
            val k = db.reviewKeepDao()
            k.upsert(ReviewKeep(8, 11))
            assertEquals(ReviewKeep(8, 11), k.get(8))
        } finally {
            db.close()
        }
    }

    @Test fun v1RowsSurviveTheWholeChain() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val file = ctx.getDatabasePath("migration-test-v1v3.db")
        file.parentFile?.mkdirs()
        file.delete()
        val v1 = SQLiteDatabase.openOrCreateDatabase(file, null)
        v1.execSQL(v2LedgerSql.replace(", `movingTo` TEXT", ""))
        v1.execSQL(
            "INSERT INTO LedgerEntry VALUES (7, 'content://media/7', 'a.jpg', 'DCIM/Camera/', 100, 1000, 10, 0, " +
                "'abc', 'Backup/Pixel/Camera/2024/a.jpg', NULL, 'VERIFIED', NULL, 5)"
        )
        v1.version = 1
        v1.close()
        val db = Room.databaseBuilder(ctx, AppDatabase::class.java, "migration-test-v1v3.db")
            .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5).allowMainThreadQueries().build()
        try {
            val e = db.ledgerDao().get(7)!!
            assertEquals(BackupStatus.VERIFIED, e.status)
            assertNull(e.movingTo)
            assertNull(e.binnedAt)
        } finally {
            db.close()
        }
    }
    @Test fun v4RowsSurviveMigrationToV5() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val file = ctx.getDatabasePath("migration-test-v4.db")
        file.parentFile?.mkdirs()
        file.delete()

        // Exact v4 schema, as generated by Room for AppDatabase version 4.
        val v4 = SQLiteDatabase.openOrCreateDatabase(file, null)
        v4.execSQL(
            "CREATE TABLE IF NOT EXISTS `LedgerEntry` (`mediaId` INTEGER NOT NULL, `localUri` TEXT NOT NULL, " +
                "`displayName` TEXT NOT NULL, `relativePath` TEXT NOT NULL, `sizeBytes` INTEGER NOT NULL, " +
                "`dateTakenMs` INTEGER NOT NULL, `dateModifiedSec` INTEGER NOT NULL, `isVideo` INTEGER NOT NULL, " +
                "`localSha256` TEXT, `remotePath` TEXT, `partPath` TEXT, `status` TEXT NOT NULL, `lastError` TEXT, " +
                "`updatedAtMs` INTEGER NOT NULL, `movingTo` TEXT, `binRequestedAt` INTEGER, `binPath` TEXT, " +
                "`binnedAt` INTEGER, PRIMARY KEY(`mediaId`))"
        )
        v4.execSQL(v2AssignmentSql)
        v4.execSQL(
            "CREATE TABLE IF NOT EXISTS `ReviewDecision` (`mediaId` INTEGER NOT NULL, `action` TEXT NOT NULL, " +
                "`decidedAt` INTEGER NOT NULL, PRIMARY KEY(`mediaId`))"
        )
        v4.execSQL(
            "CREATE TABLE IF NOT EXISTS `ReviewKeep` (`mediaId` INTEGER NOT NULL, `keptAt` INTEGER NOT NULL, " +
                "PRIMARY KEY(`mediaId`))"
        )
        v4.execSQL(
            "CREATE TABLE IF NOT EXISTS `SecondCopy` (`mediaId` INTEGER NOT NULL, `remotePath` TEXT, `partPath` TEXT, " +
                "`movingTo` TEXT, `status` TEXT NOT NULL, `sizeBytes` INTEGER NOT NULL, `sha256` TEXT, " +
                "`lastError` TEXT, `updatedAtMs` INTEGER NOT NULL, PRIMARY KEY(`mediaId`))"
        )
        v4.execSQL(
            "INSERT INTO LedgerEntry VALUES (7, 'content://media/7', 'a.jpg', 'DCIM/Camera/', 100, 1000, 10, 0, " +
                "'abc', 'Backup/Pixel/Camera/2024/a.jpg', NULL, 'VERIFIED', 'kept', 5, NULL, NULL, NULL, NULL)"
        )
        v4.execSQL("INSERT INTO SecondCopy VALUES (7, 'B2/a.jpg', NULL, NULL, 'VERIFIED', 100, 'abc', NULL, 6)")
        v4.execSQL("INSERT INTO FolderAssignment VALUES (7, 'Dog')")
        v4.version = 4
        v4.close()

        val db = Room.databaseBuilder(ctx, AppDatabase::class.java, "migration-test-v4.db")
            .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4, MIGRATION_4_5).allowMainThreadQueries().build()
        try {
            val e = db.ledgerDao().get(7)!!
            assertEquals("Backup/Pixel/Camera/2024/a.jpg", e.remotePath)
            assertEquals("kept", e.lastError)
            assertNull(e.lastCheckedAt)
            val c = db.secondCopyDao().get(7)!!
            assertEquals(SecondStatus.VERIFIED, c.status)
            assertNull(c.lastCheckedAt)
            assertEquals(FolderAssignment(7, "Dog"), db.folderAssignmentDao().get(7))

            db.ledgerDao().upsert(e.copy(lastCheckedAt = 42))
            assertEquals(42L, db.ledgerDao().get(7)!!.lastCheckedAt)
            db.secondCopyDao().upsert(c.copy(lastCheckedAt = 43))
            assertEquals(43L, db.secondCopyDao().get(7)!!.lastCheckedAt)
        } finally {
            db.close()
        }
    }
}
