package dev.photobackup.ledger

import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class MigrationTest {
    @Test fun v1RowsSurviveAndNewTableWorks() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val file = ctx.getDatabasePath("migration-test.db")
        file.parentFile?.mkdirs()
        file.delete()

        // Exact v1 schema, as generated by Room for AppDatabase version 1.
        val v1 = SQLiteDatabase.openOrCreateDatabase(file, null)
        v1.execSQL(
            "CREATE TABLE IF NOT EXISTS `LedgerEntry` (`mediaId` INTEGER NOT NULL, `localUri` TEXT NOT NULL, " +
                "`displayName` TEXT NOT NULL, `relativePath` TEXT NOT NULL, `sizeBytes` INTEGER NOT NULL, " +
                "`dateTakenMs` INTEGER NOT NULL, `dateModifiedSec` INTEGER NOT NULL, `isVideo` INTEGER NOT NULL, " +
                "`localSha256` TEXT, `remotePath` TEXT, `partPath` TEXT, `status` TEXT NOT NULL, " +
                "`lastError` TEXT, `updatedAtMs` INTEGER NOT NULL, PRIMARY KEY(`mediaId`))"
        )
        v1.execSQL(
            "INSERT INTO LedgerEntry VALUES (7, 'content://media/7', 'a.jpg', 'DCIM/Camera/', 100, 1000, 10, 0, " +
                "'abc', 'Backup/Pixel/Camera/2024/a.jpg', NULL, 'VERIFIED', NULL, 5)"
        )
        v1.version = 1
        v1.close()

        val db = Room.databaseBuilder(ctx, AppDatabase::class.java, "migration-test.db")
            .addMigrations(MIGRATION_1_2).allowMainThreadQueries().build()
        try {
            val e = db.ledgerDao().get(7)!!
            assertEquals("Backup/Pixel/Camera/2024/a.jpg", e.remotePath)
            assertEquals(BackupStatus.VERIFIED, e.status)
            assertNull(e.movingTo)
            assertEquals(emptyList<LedgerEntry>(), db.ledgerDao().withMovingTo())

            val dao = db.folderAssignmentDao()
            assertNull(dao.get(7))
            dao.set(FolderAssignment(7, "Dog"))
            assertEquals(FolderAssignment(7, "Dog"), dao.get(7))
            dao.set(FolderAssignment(7, "Cat"))
            assertEquals(listOf(FolderAssignment(7, "Cat")), dao.all())
            dao.clear(7)
            assertNull(dao.get(7))

            db.ledgerDao().upsert(e.copy(movingTo = "Backup/Pixel/Dog/2024/a.jpg"))
            assertEquals(listOf(7L), db.ledgerDao().withMovingTo().map { it.mediaId })
        } finally {
            db.close()
        }
    }
}
