package dev.photobackup.ledger

import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class SecondCopyDaoTest {
    private lateinit var db: AppDatabase
    private lateinit var dao: SecondCopyDao

    @Before fun setUp() {
        db = Room.inMemoryDatabaseBuilder(ApplicationProvider.getApplicationContext(), AppDatabase::class.java)
            .allowMainThreadQueries().build()
        dao = db.secondCopyDao()
    }

    @After fun tearDown() = db.close()

    private fun row(id: Long, status: SecondStatus = SecondStatus.VERIFIED, remote: String? = "B/a.jpg", part: String? = null) =
        SecondCopy(id, remote, part, null, status, 100, "abc", null, 5)

    @Test fun upsertGetRoundTripsAndReplaces() = runBlocking {
        val r = row(1).copy(lastError = "boom")
        dao.upsert(r)
        assertEquals(r, dao.get(1))
        assertNull(dao.get(2))
        dao.upsert(r.copy(status = SecondStatus.FAILED))
        assertEquals(SecondStatus.FAILED, dao.get(1)!!.status)
    }

    @Test fun observeAllAndByStatus() = runBlocking {
        dao.upsert(row(1)); dao.upsert(row(2, SecondStatus.FAILED)); dao.upsert(row(3, SecondStatus.UPLOADING, null, "x.part"))
        assertEquals(setOf(1L, 2L, 3L), dao.observeAll().first().map { it.mediaId }.toSet())
        assertEquals(listOf(2L), dao.byStatus(SecondStatus.FAILED).map { it.mediaId })
        assertEquals(listOf(3L), dao.byStatus(SecondStatus.UPLOADING).map { it.mediaId })
    }

    @Test fun beginMoveIsConditionalAndEndMoveCompletes() = runBlocking {
        dao.upsert(row(1))
        assertFalse(dao.beginMove(1, "other/a.jpg", "B/Dog/a.jpg", 9))
        assertNull(dao.get(1)!!.movingTo)
        assertTrue(dao.beginMove(1, "B/a.jpg", "B/Dog/a.jpg", 9))
        assertEquals(listOf(1L), dao.withMovingTo().map { it.mediaId })
        assertFalse(dao.beginMove(1, "B/a.jpg", "B/Cat/a.jpg", 10)) // already moving
        dao.endMove(1, "B/Dog/a.jpg", null, null, 11)
        val e = dao.get(1)!!
        assertEquals("B/Dog/a.jpg", e.remotePath)
        assertNull(e.movingTo)
        assertEquals(11L, e.updatedAtMs)
        assertEquals(emptyList<SecondCopy>(), dao.withMovingTo())
    }

    @Test fun beginMoveRefusedWhilePartFileExists() = runBlocking {
        dao.upsert(row(1, SecondStatus.UPLOADING, "B/a.jpg", "x.part"))
        assertFalse(dao.beginMove(1, "B/a.jpg", "B/Dog/a.jpg", 9))
    }

    @Test fun endMoveIfOnlyEndsTheExpectedMove() = runBlocking {
        dao.upsert(row(1))
        assertTrue(dao.beginMove(1, "B/a.jpg", "B/Dog/a.jpg", 9))
        assertFalse(dao.endMoveIf(1, "B/Cat/a.jpg", "B/Cat/a.jpg", null, null, 10))
        assertEquals("B/Dog/a.jpg", dao.get(1)!!.movingTo)
        assertTrue(dao.endMoveIf(1, "B/Dog/a.jpg", "B/Dog/a.jpg", null, null, 11))
        assertEquals("B/Dog/a.jpg", dao.get(1)!!.remotePath)
        assertNull(dao.get(1)!!.movingTo)
        assertFalse(dao.endMoveIf(1, "B/Dog/a.jpg", "B/x.jpg", null, null, 12)) // no move recorded any more
    }

    @Test fun withPartPathAllAndSetLastError() = runBlocking {
        dao.upsert(row(1)); dao.upsert(row(2, SecondStatus.FAILED, null, "x.part"))
        assertEquals(listOf(2L), dao.withPartPath().map { it.mediaId })
        assertEquals(setOf(1L, 2L), dao.all().map { it.mediaId }.toSet())
        dao.setLastError(1, "boom", 7)
        assertEquals("boom", dao.get(1)!!.lastError)
        assertEquals(7L, dao.get(1)!!.updatedAtMs)
        assertEquals(SecondStatus.VERIFIED, dao.get(1)!!.status)
        dao.delete(1)
        assertNull(dao.get(1))
        assertEquals(listOf(2L), dao.all().map { it.mediaId })
    }

    @Test fun clearRemovesEverything() = runBlocking {
        dao.upsert(row(1)); dao.upsert(row(2))
        dao.clear()
        assertEquals(emptyList<SecondCopy>(), dao.observeAll().first())
    }

    @Test fun v3RowsSurviveMigrationToV4() = runBlocking {
        val ctx = ApplicationProvider.getApplicationContext<android.content.Context>()
        val file = ctx.getDatabasePath("migration-test-v3.db")
        file.parentFile?.mkdirs()
        file.delete()

        // Exact v3 schema, as generated by Room for AppDatabase version 3.
        val v3 = SQLiteDatabase.openOrCreateDatabase(file, null)
        v3.execSQL(
            "CREATE TABLE IF NOT EXISTS `LedgerEntry` (`mediaId` INTEGER NOT NULL, `localUri` TEXT NOT NULL, " +
                "`displayName` TEXT NOT NULL, `relativePath` TEXT NOT NULL, `sizeBytes` INTEGER NOT NULL, " +
                "`dateTakenMs` INTEGER NOT NULL, `dateModifiedSec` INTEGER NOT NULL, `isVideo` INTEGER NOT NULL, " +
                "`localSha256` TEXT, `remotePath` TEXT, `partPath` TEXT, `status` TEXT NOT NULL, `lastError` TEXT, " +
                "`updatedAtMs` INTEGER NOT NULL, `movingTo` TEXT, `binRequestedAt` INTEGER, `binPath` TEXT, " +
                "`binnedAt` INTEGER, PRIMARY KEY(`mediaId`))"
        )
        v3.execSQL(
            "CREATE TABLE IF NOT EXISTS `FolderAssignment` (`mediaId` INTEGER NOT NULL, `folder` TEXT NOT NULL, " +
                "PRIMARY KEY(`mediaId`))"
        )
        v3.execSQL(
            "CREATE TABLE IF NOT EXISTS `ReviewDecision` (`mediaId` INTEGER NOT NULL, `action` TEXT NOT NULL, " +
                "`decidedAt` INTEGER NOT NULL, PRIMARY KEY(`mediaId`))"
        )
        v3.execSQL(
            "CREATE TABLE IF NOT EXISTS `ReviewKeep` (`mediaId` INTEGER NOT NULL, `keptAt` INTEGER NOT NULL, " +
                "PRIMARY KEY(`mediaId`))"
        )
        v3.execSQL(
            "INSERT INTO LedgerEntry VALUES (7, 'content://media/7', 'a.jpg', 'DCIM/Camera/', 100, 1000, 10, 0, " +
                "'abc', 'Backup/Pixel/Camera/2024/a.jpg', NULL, 'VERIFIED', NULL, 5, NULL, NULL, NULL, NULL)"
        )
        v3.execSQL("INSERT INTO FolderAssignment VALUES (7, 'Dog')")
        v3.execSQL("INSERT INTO ReviewDecision VALUES (7, 'JUNK', 10)")
        v3.execSQL("INSERT INTO ReviewKeep VALUES (8, 11)")
        v3.version = 3
        v3.close()

        val mdb = Room.databaseBuilder(ctx, AppDatabase::class.java, "migration-test-v3.db")
            .addMigrations(MIGRATION_1_2, MIGRATION_2_3, MIGRATION_3_4).allowMainThreadQueries().build()
        try {
            val e = mdb.ledgerDao().get(7)!!
            assertEquals("Backup/Pixel/Camera/2024/a.jpg", e.remotePath)
            assertEquals(BackupStatus.VERIFIED, e.status)
            assertEquals(FolderAssignment(7, "Dog"), mdb.folderAssignmentDao().get(7))
            assertEquals(7L, mdb.reviewDecisionDao().lastDecided()!!.mediaId)
            assertEquals(ReviewKeep(8, 11), mdb.reviewKeepDao().get(8))

            val s = mdb.secondCopyDao()
            assertEquals(emptyList<SecondCopy>(), s.observeAll().first())
            val r = SecondCopy(7, "B2/a.jpg", null, null, SecondStatus.VERIFIED, 100, "abc", null, 6)
            s.upsert(r)
            assertEquals(r, s.get(7))
        } finally {
            mdb.close()
        }
    }
}
